/// Whether `c` is punctuation that belongs with an adjacent first letter.
fn is_punctuation(c: char) -> bool {
    in_ranges(c, PUNCTUATION)
}

/// Whether `c` is a combining mark, which belongs to the letter it sits on.
fn is_combining(c: char) -> bool {
    in_ranges(c, COMBINING)
}

fn in_ranges(c: char, ranges: &[(u32, u32)]) -> bool {
    let c = c as u32;
    ranges
        .binary_search_by(|&(low, high)| {
            if c < low {
                std::cmp::Ordering::Greater
            } else if c > high {
                std::cmp::Ordering::Less
            } else {
                std::cmp::Ordering::Equal
            }
        })
        .is_ok()
}

/// How many bytes of `text` the `::first-letter` box covers, or `None` when
/// there is no first letter in it at all.
///
/// §5.12.2: punctuation on either side of the letter comes with it, and a
/// string that is *only* punctuation has no first letter — the box is not
/// generated and the next line's text is not promoted into it, because the
/// first letter of a block is the first letter of its **first line**.
///
/// Returns a byte count so the caller can split the run without re-scanning.
pub fn first_letter_len(text: &str) -> Option<usize> {
    let mut chars = text.char_indices().peekable();

    // Leading punctuation: `"`, `(`, `¿`.
    let mut letter = None;
    for (index, c) in chars.by_ref() {
        if !is_punctuation(c) {
            letter = Some((index, c));
            break;
        }
    }
    let (index, c) = letter?;
    let mut end = index + c.len_utf8();

    // The letter's own combining marks, then punctuation after it.
    while let Some(&(index, c)) = chars.peek() {
        if !is_combining(c) {
            break;
        }
        end = index + c.len_utf8();
        chars.next();
    }
    while let Some(&(index, c)) = chars.peek() {
        if !is_punctuation(c) {
            break;
        }
        end = index + c.len_utf8();
        chars.next();
    }
    Some(end)
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The part of `text` a `::first-letter` box would cover.
    fn first(text: &str) -> Option<&str> {
        Some(&text[..first_letter_len(text)?])
    }

    #[test]
    fn a_plain_word_gives_up_its_first_letter() {
        assert_eq!(first("Test"), Some("T"));
    }

    #[test]
    fn punctuation_on_either_side_comes_with_the_letter() {
        // The whole point of §5.12.2, and the shape of the 339 tests in the
        // suite that assert it one codepoint at a time.
        assert_eq!(first(")T)est"), Some(")T)"));
        assert_eq!(first("\u{201c}Once"), Some("\u{201c}O"));
        assert_eq!(first("\u{00bf}Qu\u{00e9}"), Some("\u{00bf}Q"));
    }

    #[test]
    fn a_combining_mark_belongs_to_the_letter_it_sits_on() {
        // `e` + U+0301 is one letter to a reader, and splitting between them
        // would leave the accent behind in a different font size.
        assert_eq!(first("e\u{0301}tude"), Some("e\u{0301}"));
    }

    #[test]
    fn punctuation_alone_has_no_first_letter() {
        // §5.12.2: the first letter is the first letter of the first *line*.
        // A line with no letter on it generates no box rather than reaching
        // down into the next one.
        assert_eq!(first("!!!"), None);
        assert_eq!(first(""), None);
    }

    #[test]
    fn the_five_punctuation_classes_are_all_here() {
        // One representative of each class the spec names, so a regenerated
        // table that lost a class fails here rather than in a reftest.
        for (c, class) in [
            ('(', "Ps"),
            (')', "Pe"),
            ('\u{2018}', "Pi"),
            ('\u{2019}', "Pf"),
            ('!', "Po"),
        ] {
            assert!(is_punctuation(c), "{class} is missing from the table");
        }
        assert!(!is_punctuation('T'), "a letter is not punctuation");
        assert!(!is_punctuation(' '), "a space is not punctuation");
    }

    #[test]
    fn a_supplementary_plane_codepoint_is_found_too() {
        // U+10A52 is in the suite. A table searched as `u16` would miss it,
        // and a linear scan would find it — so this is a binary-search test as
        // much as a Unicode one.
        assert!(is_punctuation('\u{10A52}'));
        assert_eq!(first("\u{10A52}T\u{10A52}est"), Some("\u{10A52}T\u{10A52}"));
    }
}
