//! `::first-letter`, and the Unicode question it turns on.
//!
//! CSS 2.1 §5.12.2 does not say "the first character". It says the first
//! letter, together with any punctuation that precedes or follows it — quotes,
//! brackets, an opening inverted question mark — because `"Once` should drop-cap
//! as `"O` and not as `"`. The classes it names are Unicode's `Ps`, `Pe`, `Pi`,
//! `Pf` and `Po`, and a combining mark on the letter goes with the letter.
//!
//! This lives in `text` rather than in `layout` because it is a question about
//! characters, not about boxes: layout asks how much of a string the first
//! letter is and splits the run there.
//!
//! **The tables below are generated.** They are the five punctuation classes
//! and the three combining-mark classes of Unicode 14.0.0, as ranges. To
//! rebuild them, from any Python whose `unicodedata` is the version you want:
//!
