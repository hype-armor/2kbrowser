//! for cp in range(0x110000): unicodedata.category(chr(cp))
//! ```
//!
//! collecting `Ps Pe Pi Pf Po` into `PUNCTUATION` and `Mn Mc Me` into
//! `COMBINING`, coalescing adjacent codepoints into ranges. A dependency would
//! keep itself current where this will quietly age; it would also carry the
//! whole general-category table for a question asked about some five hundred
//! codepoints. The staleness is the cost, and it is written down here rather
//! than left to be discovered.

